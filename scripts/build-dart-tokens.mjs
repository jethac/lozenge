#!/usr/bin/env node
// Generates the Dart token engine for lozenge_flutter from the SAME
// tokens/*.json the CSS engine is built from, plus a cross-engine fixture
// of resolved colors (computed by the shared JS resolver) that the Dart
// test suite must reproduce — the two engines cannot drift silently.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { converter } from "culori";
import { resolveToken, clampedRgba } from "./lib/resolve.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ramps = JSON.parse(readFileSync(join(root, "tokens/ramps.json"), "utf8"));
const sys = JSON.parse(readFileSync(join(root, "tokens/sys.json"), "utf8"));
delete ramps.$comment;

const toOklch = converter("oklch");
const fmt = (n, dp = 6) => Number(n.toFixed(dp));
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

// ------------------------------------------------------------- tokens.g.dart
let rampsDart = "";
for (const [ramp, steps] of Object.entries(ramps)) {
  const entries = Object.entries(steps)
    .map(([step, hex]) => {
      const c = toOklch(hex);
      return `'${step}': LzOklch(${fmt(c.l)}, ${fmt(c.c ?? 0)}, ${fmt(c.h ?? 0, 2)})`;
    })
    .join(", ");
  rampsDart += `  '${ramp}': {${entries}},\n`;
}

function defDart(def) {
  const parts = [`ref: '${def.ref}'`];
  if (def.lShift) parts.push(`lShift: ${def.lShift}`);
  if (def.k) parts.push(`k: ${def.k}`);
  if (def.ck) parts.push(`ck: ${def.ck}`);
  if (def.cScale !== undefined && def.cScale !== 1)
    parts.push(`cScale: ${def.cScale}`);
  if (def.alpha !== undefined) parts.push(`alpha: ${def.alpha}`);
  return `LzTokenDef(${parts.join(", ")})`;
}

let sysDart = "";
let gettersDart = "";
for (const [name, schemes] of Object.entries(sys.tokens)) {
  sysDart += `  '${name}': LzTokenSchemes(light: ${defDart(schemes.light)}, dark: ${defDart(schemes.dark)}),\n`;
  gettersDart += `  Color get ${camel(name)} => resolve('${name}');\n`;
}

const dart = `// AUTO-GENERATED by scripts/build-dart-tokens.mjs — do not edit.
// Source of truth: tokens/ramps.json + tokens/sys.json (same files that
// generate the CSS engine). Regenerate with: npm run tokens:dart
//
// ignore_for_file: prefer_single_quotes

part of '../lozenge_flutter.dart';

const double lzDefaultAccentHue = ${fmt(toOklch(ramps.blue["400"]).h, 2)};

const Map<String, Map<String, LzOklch>> lzRamps = {
${rampsDart}};

const Map<String, LzTokenSchemes> lzSysTokens = {
${sysDart}};

/// Lozenge status-variant families, as used by lozenges/messages/flags.
const Map<String, String> lzLozengeVariants = {
  'default': 'neutral', 'inprogress': 'info', 'moved': 'warning',
  'new': 'discovery', 'removed': 'danger', 'success': 'success',
};

/// Motion tokens (mirrors --lz-motion-* / --lz-ease-*).
class LzMotion {
  static const fast = Duration(milliseconds: 100);
  static const medium = Duration(milliseconds: 200);
  static const slow = Duration(milliseconds: 300);
  static const deliberate = Duration(milliseconds: 700);
  static const standard = Cubic(0.2, 0, 0, 1);
  static const entrance = Cubic(0.15, 1, 0.3, 1);
  static const exit = Cubic(0.6, 0, 1, 0.6);
}

/// Typed accessors for every system token.
extension LzSysColors on LzThemeData {
${gettersDart}}
`;

const pkg = join(root, "packages/lozenge_flutter");
mkdirSync(join(pkg, "lib/src"), { recursive: true });
writeFileSync(join(pkg, "lib/src/tokens.g.dart"), dart);

// ------------------------------------------------------------- fixture
const fixture = [];
for (const scheme of ["light", "dark"]) {
  for (const dial of [-1, -0.5, 0, 0.5, 1]) {
    for (const hue of [90, 260.48]) {
      for (const name of Object.keys(sys.tokens)) {
        const tok = resolveToken(ramps, sys, name, scheme, dial, hue, 1);
        const { r, g, b, a } = clampedRgba(tok);
        fixture.push({
          token: name,
          scheme,
          dial,
          hue,
          rgba: [fmt(r), fmt(g), fmt(b), fmt(a)],
        });
      }
    }
  }
}
mkdirSync(join(pkg, "test/fixtures"), { recursive: true });
writeFileSync(
  join(pkg, "test/fixtures/resolved_colors.json"),
  JSON.stringify(fixture) + "\n"
);

console.log(
  `dart engine: ${Object.keys(sys.tokens).length} sys tokens → tokens.g.dart; fixture: ${fixture.length} resolved colors`
);
